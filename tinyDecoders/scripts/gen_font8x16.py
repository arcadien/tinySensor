def read_rows(path):
    """Returns {code point: 16 row bytes, MSB = leftmost pixel}."""
    glyphs = {}
    with open(path) as bdf:
        lines = iter(bdf.read().splitlines())
    for line in lines:
        if line.startswith("ENCODING "):
            code = int(line.split()[1])
        elif line.startswith("BBX "):
            # Every glyph must fill the cell, so rows map 1:1 to pixels
            if line.split()[1:] != ["8", "16", "0", "-4"]:
                sys.exit(f"U+{code:04X}: unexpected {line}")
        elif line == "BITMAP":
            glyphs[code] = [int(next(lines), 16) for _ in range(16)]
    return glyphs


def to_pages(rows):
    """Row bytes to SSD1306 page bytes: page, then column, bit 0 on top."""
    return [
        sum(((rows[page * 8 + bit] >> (7 - col)) & 1) << bit for bit in range(8))
        for page in range(2)
        for col in range(8)
    ]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    glyphs = read_rows(sys.argv[1])
    out = ["/*", " * Generated by tinyDecoders/scripts/gen_font8x16.py, do not edit.", " *"]
    out += [(" * " + line).rstrip() for line in LICENSE.splitlines()]
    out += [" */", "", "#pragma once", "", "#include <stdint.h>", ""]
    out += ["// clang-format off"]
    keys = ", ".join(f"0x{ord(c):02X}" for c in CHARACTERS)
    out += [f"static const uint8_t GlyphCount = {len(CHARACTERS)};", ""]
    out += [f"static const char GlyphChars[GlyphCount] PROGMEM = {{{keys}}};", ""]
    out += ["static const uint8_t GlyphBytes[GlyphCount][16] PROGMEM = {"]
    for c in CHARACTERS:
        code = DEGREE if c == "\x7f" else ord(c)
        data = ", ".join(f"0x{b:02X}" for b in to_pages(glyphs[code]))
        out += [f"    {{{data}}},  // U+{code:04X}"]
    out += ["};", "// clang-format on", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
